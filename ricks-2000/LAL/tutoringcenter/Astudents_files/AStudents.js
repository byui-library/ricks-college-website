function calculateGrade(myForm)
{
  var numChecked = 0
  var grade
  var header
  var tipWindow

  // counts the number of checkboxes that are checked.
  for (var i = 0; i < numQuestions; ++i)
    if (eval("myForm.rad" + i + "[0].checked"))
      ++numChecked

  // finds the grade.
  if (numChecked >= 80)
    grade = "n A"
  else if (numChecked >= 50)
    grade = " B"
  else if (numChecked >= 25)
    grade = " C"
  else
    grade = "Needs Improvement"

  // makes new page and goes there.
  tipWindow = window.open('score.html', '')
  tipWindow.document.open("text/html")
  tipWindow.document.writeln("<html>\n<head>\n<title>Your Score for College Success tips</title>\n</head>")
  tipWindow.document.writeln("<style type='text/css'>\nbody {background-image: url(AStudents_files/AStudents.jpg);\nbackground-position: -100px 0px;\nbackground-attachment: fixed;}\n</style>")
  tipWindow.document.writeln("<body>\n<center>\n<span style='font-size:18.0ptfont-family:Arial'><b>Your score ")
  if (grade == "Needs Improvement")
    tipWindow.document.write(grade)
  else 
    tipWindow.document.write("is a" + grade)
  tipWindow.document.write("</b></span>\n</center>\n<p>\n<span style='font-size:12.0ptfont-family:Arial'>\n<b>The following are the " + (numQuestions - numChecked) + " tips that you need to work on.</b>\n<table cellpadding=5>")
  headNum = 1
  for (var i = 0; i < numQuestions; ++i)
  {
    if (i == eval("t" + headNum))
    {
      header = eval("t_" + headNum)
      tipWindow.document.writeln("<tr><td colspan=2><i><u><b>" + header + "</b></u></i><p></td></tr>")
      headNum++
    }
    if (!eval("myForm.rad" + i + "[0].checked"))
      tipWindow.document.writeln("<tr><td width=20 align=right valign=top>" + myForm.tip[i].value + "</td></tr>")
  }
  tipWindow.document.writeln("</table></span>\n</body>\n<html>")
  tipWindow.document.close()
}

